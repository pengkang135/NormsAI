def resolve_gb_code(chap_id: int, norm_name: str) -> str | None:
    rules = CHAPTER_KEYWORD_RULES.get(chap_id)
    if not rules or not norm_name:
        return None
    for pattern, code in rules:
        if re.search(pattern, norm_name):
            return code
    return None


def _division_code_to_num(div: str) -> str:
    return div.split(".", 1)[1]


def create_schema(con: sqlite3.Connection) -> None:
    cur = con.cursor()
    cur.execute("""
        CREATE TABLE chapter (
            chap_ID INTEGER PRIMARY KEY,
            chap_PID INTEGER NOT NULL,
            chap_Name TEXT,
            chap_Content TEXT,
            chap_code TEXT,
            chap_Index TEXT
        )
    """)
    cur.execute("""
        CREATE TABLE Norm (
            norm_ID INTEGER PRIMARY KEY,
            chap_ID INTEGER NOT NULL,
            chap_Code TEXT,
            norm_SortID INTEGER,
            norm_Specialty TEXT,
            norm_Code TEXT,
            norm_Name TEXT,
            norm_Units TEXT,
            norm_BaseUnits TEXT,
            norm_UnitsQuotiety REAL,
            norm_ManPrice REAL,
            norm_MaterialPrice REAL,
            norm_MachinePrice REAL,
            norm_OtherPrice REAL,
            norm_MainMaterialPrice REAL,
            norm_EquipmentPrice REAL,
            norm_AttachTag1 TEXT,
            norm_AttachTag INTEGER,
            norm_isEntity TEXT,
            norm_Tag INTEGER,
            norm_direct TEXT,
            norm_Alias TEXT,
            Norm_Content INT
        )
    """)
    cur.execute("""
        CREATE TABLE Consumption (
            cons_ID INTEGER PRIMARY KEY,
            kind_ID INTEGER, kind_Code TEXT, cons_Code TEXT,
            cons_Alias TEXT, cons_Name TEXT, cons_Standard TEXT,
            cons_Units TEXT, cons_Price DECIMAL, cons_Market DECIMAL,
            cons_Supply REAL, cons_ThreeTag TEXT, cons_ThreeQuotiety REAL,
            cons_Style INTEGER, cons_UnitQuotiety INTEGER,
            cons_CompositeStyle INTEGER, cons_IsCalculate TEXT,
            cons_CalculateBasic TEXT
        )
    """)
    cur.execute("""
        CREATE TABLE Content (
            cont_ID INTEGER PRIMARY KEY,
            norm_ID INTEGER NOT NULL, cons_ID INTEGER NOT NULL,
            cont_Amount REAL, cont_Type INTEGER,
            cont_IsMainMaterial TEXT, cont_IsCalculatePrice TEXT
        )
    """)
    cur.execute("""
        CREATE TABLE enterprise_item (
            code TEXT PRIMARY KEY, division TEXT, sub_level3 TEXT,
            name TEXT, unit TEXT, item_feature TEXT,
            calc_rule TEXT, work_content TEXT, gb_ref TEXT, chap_ID INTEGER
        )
    """)
    # 数据来源溯源表（隐性元数据，不参与浏览器展示）
    # 一条 Norm 对应一条 source 记录。将来吸收其他定额库时可辨识数据来源。
    cur.execute("""
        CREATE TABLE norm_source (
            norm_ID INTEGER PRIMARY KEY,
            source_lib TEXT NOT NULL,
            source_norm_id INTEGER,
            source_norm_code TEXT,
            source_chap_id INTEGER,
            source_chap_name TEXT,
            source_chap_path TEXT,
            source_book TEXT,
            import_time TEXT,
            FOREIGN KEY(norm_ID) REFERENCES Norm(norm_ID)
        )
    """)
    cur.execute("CREATE INDEX idx_norm_chap ON Norm(chap_ID)")
    cur.execute("CREATE INDEX idx_content_norm ON Content(norm_ID)")
    cur.execute("CREATE INDEX idx_content_cons ON Content(cons_ID)")
    cur.execute("CREATE INDEX idx_norm_source_lib ON norm_source(source_lib)")
    cur.execute("CREATE INDEX idx_norm_source_code ON norm_source(source_norm_code)")
    con.commit()


def _build_chap_path(bj: sqlite3.Connection, chap_id: int) -> tuple[str, str]:
    """返回 (章节完整路径, 顶层 book 名称)"""
    chain = []
    cid = chap_id
    while cid and cid != 0:
        r = bj.execute('SELECT chap_PID, chap_Name FROM chapter WHERE chap_ID=?', (cid,)).fetchone()
        if not r:
            break
        chain.append(r[1])
        cid = r[0]
    chain.reverse()
    book = chain[0] if chain else ""
    return (" > ".join(chain), book)


def build_chapters(dst: sqlite3.Connection, fw: sqlite3.Connection) -> dict[str, int]:
    """构建 C 册 division/sub_division/enterprise_item 三级章节树。
    因 C 册 division 编号可能 >2 位（如 C.20, C.21, C.22, C.33），
    chap_ID 编码为 int(div_num)*1_000_000 + int(sub)*1000 + seq。
    """
    cur = dst.cursor()
    cur_r = fw.cursor()

    # divisions
    for r in cur_r.execute("SELECT code, name, description FROM division ORDER BY code").fetchall():
        code, name, desc = r
        div_num = _division_code_to_num(code)
        div_chap_id = int(div_num) * 1_000_000
        cur.execute(
            "INSERT INTO chapter VALUES (?, ?, ?, ?, ?, ?)",
            (div_chap_id, 0, f"{code} {name}", desc or "", div_num, div_num),
        )

    # sub_divisions
    for r in cur_r.execute("SELECT division_code, sub_code, name FROM sub_division ORDER BY division_code, sub_code").fetchall():
        div, sub, sname = r
        div_num = _division_code_to_num(div)
        div_chap_id = int(div_num) * 1_000_000
        sub_chap_id = div_chap_id + int(sub) * 1000
        chap_code = f"{div_num}.{sub}"
        cur.execute(
            "INSERT INTO chapter VALUES (?, ?, ?, ?, ?, ?)",
            (sub_chap_id, div_chap_id, f"{div}.{sub} {sname}", "", chap_code, chap_code),
        )

    # enterprise_item (L3)
    item_chap_ids: dict[str, int] = {}
    for r in cur_r.execute(
        "SELECT code, division, sub_level3, name, unit, item_feature, calc_rule, work_content, gb_ref "
        "FROM enterprise_item ORDER BY code"
    ).fetchall():
        code, div, sub, name, unit, feat, rule, wc, gb_ref = r
        parts = code.split(".")
        if len(parts) != 4:
            continue
        div_num = _division_code_to_num(div)
        div_chap_id = int(div_num) * 1_000_000
        sub_chap_id = div_chap_id + int(sub) * 1000
        seq = int(parts[3])
        item_chap_id = sub_chap_id + seq
        chap_code = f"{div_num}.{sub}.{parts[3]}"

        content_parts = []
        if feat: content_parts.append(f"【项目特征】{feat}")
        if rule: content_parts.append(f"【计量规则】{rule}")
        if wc: content_parts.append(f"【工作内容】{wc}")
        if gb_ref: content_parts.append(f"【GB编码】{gb_ref}")
        chap_content = "\n".join(content_parts)

        cur.execute(
            "INSERT INTO chapter VALUES (?, ?, ?, ?, ?, ?)",
            (item_chap_id, sub_chap_id, f"{code} {name}", chap_content, chap_code, chap_code),
        )
        item_chap_ids[code] = item_chap_id
        cur.execute(
            "INSERT INTO enterprise_item VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
            (code, div, sub, name, unit, feat, rule, wc, gb_ref, item_chap_id),
        )

    # 追加企业扩展项
    for ext in ITEMS_GB_EXTENSIONS:
        code, div, sub, name, unit, feat, rule, wc, gb_ref = ext
        parts = code.split(".")
        if len(parts) != 4:
            continue
        div_num = _division_code_to_num(div)
        div_chap_id = int(div_num) * 1_000_000
        sub_chap_id = div_chap_id + int(sub) * 1000
        seq = int(parts[3])
        item_chap_id = sub_chap_id + seq
        if item_chap_id in [v for v in item_chap_ids.values()]:
            print(f"  [WARN] 扩展项 {code} 与既有 enterprise_item 冲突，跳过")
            continue
        chap_code = f"{div_num}.{sub}.{parts[3]}"
        content_parts = []
        if feat: content_parts.append(f"【项目特征】{feat}")
        if rule: content_parts.append(f"【计量规则】{rule}")
        if wc: content_parts.append(f"【工作内容】{wc}")
        content_parts.append("【备注】企业定额扩展分项（非 GB2024 官方清单）")
        chap_content = "\n".join(content_parts)
        cur.execute(
            "INSERT INTO chapter VALUES (?, ?, ?, ?, ?, ?)",
            (item_chap_id, sub_chap_id, f"{code} {name}", chap_content, chap_code, chap_code),
        )
        item_chap_ids[code] = item_chap_id
        cur.execute(
            "INSERT INTO enterprise_item VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
            (code, div, sub, name, unit, feat, rule, wc, gb_ref, item_chap_id),
        )

    dst.commit()
    return item_chap_ids


def copy_norms_and_deps(
    dst: sqlite3.Connection,
    bj: sqlite3.Connection,
    item_chap_ids: dict[str, int],
) -> dict:
    from datetime import datetime
    cur = dst.cursor()
    stats = {"norms": 0, "contents": 0, "cons": 0,
             "unmapped_chapters": [], "unmapped_norms": 0, "split_counts": {}}

    SOURCE_LIB = "北京2012_建设工程计价依据_预算定额"
    import_time = datetime.now().isoformat(timespec="seconds")

    # 预缓存所有映射章节的路径与 book
    chap_meta: dict[int, tuple[str, str, str]] = {}
    for bj_chap_id in BJ_CHAPTER_TO_GB.keys():
        chap_name_row = bj.execute("SELECT chap_Name FROM chapter WHERE chap_ID=?", (bj_chap_id,)).fetchone()
        chap_name = chap_name_row[0] if chap_name_row else ""
        chap_path, book = _build_chap_path(bj, bj_chap_id)
        chap_meta[bj_chap_id] = (chap_name, chap_path, book)

    kept_norm_ids: list[int] = []
    split_counts: dict[int, dict[str, int]] = {}

    for bj_chap_id, default_code in BJ_CHAPTER_TO_GB.items():
        default_chap_id = item_chap_ids.get(default_code)
        if default_chap_id is None:
            print(f"  [WARN] enterprise_item 中无 {default_code}（对应 BJ chap {bj_chap_id}）")
            continue
        has_rules = bj_chap_id in CHAPTER_KEYWORD_RULES
        chap_name, chap_path, book = chap_meta[bj_chap_id]
        for r in bj.execute("SELECT * FROM Norm WHERE chap_ID=?", (bj_chap_id,)).fetchall():
            gb_code = default_code
            target_chap_id = default_chap_id
            if has_rules:
                refined = resolve_gb_code(bj_chap_id, r["norm_Name"] or "")
                if refined and refined in item_chap_ids:
                    gb_code = refined
                    target_chap_id = item_chap_ids[refined]
                split_counts.setdefault(bj_chap_id, {}).setdefault(gb_code, 0)
                split_counts[bj_chap_id][gb_code] += 1
            cur.execute(
                """INSERT INTO Norm VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)""",
                (
                    r["norm_ID"], target_chap_id, gb_code, r["norm_SortID"], r["norm_Specialty"],
                    r["norm_Code"], r["norm_Name"], r["norm_Units"], r["norm_BaseUnits"], r["norm_UnitsQuotiety"],
                    r["norm_ManPrice"], r["norm_MaterialPrice"], r["norm_MachinePrice"], r["norm_OtherPrice"],
                    r["norm_MainMaterialPrice"], r["norm_EquipmentPrice"],
                    r["norm_AttachTag1"], r["norm_AttachTag"], r["norm_isEntity"], r["norm_Tag"],
                    r["norm_direct"], r["norm_Alias"], r["Norm_Content"],
                ),
            )
            # 写入 norm_source 元数据（隐性溯源）
            cur.execute(
                """INSERT INTO norm_source (
                    norm_ID, source_lib, source_norm_id, source_norm_code,
                    source_chap_id, source_chap_name, source_chap_path, source_book, import_time
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)""",
                (
                    r["norm_ID"], SOURCE_LIB, r["norm_ID"], r["norm_Code"],
                    bj_chap_id, chap_name, chap_path, book, import_time,
                ),
            )
            kept_norm_ids.append(r["norm_ID"])
    stats["norms"] = len(kept_norm_ids)
    stats["split_counts"] = split_counts

    # 未映射 book15-19 章节
    all_bj_chaps = {r[0] for r in bj.execute(
        "SELECT DISTINCT chap_ID FROM Norm "
        "WHERE chap_ID >= 1500000000 AND chap_ID < 2000000000"
    ).fetchall()}
    unmapped = all_bj_chaps - set(BJ_CHAPTER_TO_GB.keys())
    for cid in sorted(unmapped):
        n = bj.execute("SELECT COUNT(*) FROM Norm WHERE chap_ID=?", (cid,)).fetchone()[0]
        stats["unmapped_chapters"].append((cid, n))
        stats["unmapped_norms"] += n

    # Content + Consumption
    if kept_norm_ids:
        BATCH = 500
        referenced_cons_ids: set[int] = set()
        for i in range(0, len(kept_norm_ids), BATCH):
            batch = kept_norm_ids[i:i+BATCH]
            kp = ",".join(["?"] * len(batch))
            for r in bj.execute(f"SELECT * FROM Content WHERE norm_ID IN ({kp}) ORDER BY cont_ID", batch).fetchall():
                cur.execute(
                    "INSERT INTO Content (cont_ID, norm_ID, cons_ID, cont_Amount, cont_Type, cont_IsMainMaterial, cont_IsCalculatePrice) "
                    "VALUES (?, ?, ?, ?, ?, ?, ?)",
                    (r["cont_ID"], r["norm_ID"], r["cons_ID"], r["cont_Amount"], r["cont_Type"],
                     r["cont_IsMainMaterial"], r["cont_IsCalculatePrice"]),
                )
                stats["contents"] += 1
                referenced_cons_ids.add(r["cons_ID"])

        cons_ids = list(referenced_cons_ids)
        for i in range(0, len(cons_ids), BATCH):
            batch = cons_ids[i:i+BATCH]
            kc = ",".join(["?"] * len(batch))
            for r in bj.execute(f"SELECT * FROM Consumption WHERE cons_ID IN ({kc})", batch).fetchall():
                cur.execute(
                    "INSERT INTO Consumption VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
                    (
                        r["cons_ID"], r["kind_ID"], r["kind_Code"], r["cons_Code"], r["cons_Alias"], r["cons_Name"],
                        r["cons_Standard"], r["cons_Units"], r["cons_Price"], r["cons_Market"], r["cons_Supply"],
                        r["cons_ThreeTag"], r["cons_ThreeQuotiety"], r["cons_Style"], r["cons_UnitQuotiety"],
                        r["cons_CompositeStyle"], r["cons_IsCalculate"], r["cons_CalculateBasic"],
                    ),
                )
                stats["cons"] += 1

    dst.commit()
    return stats


def main() -> None:
    if OUT_DB.exists():
        import shutil, time
        backup_dir = OUT_DB.parent / "backup"
        backup_dir.mkdir(exist_ok=True)
        bak = backup_dir / f"{OUT_DB.stem}.pre-full-{int(time.time())}.bak"
        shutil.copy2(OUT_DB, bak)
        print(f"[BACKUP] backup/{bak.name}")
        OUT_DB.unlink()

    fw = sqlite3.connect(str(FRAMEWORK_DB)); fw.row_factory = sqlite3.Row
    bj = sqlite3.connect(str(BEIJING_DB)); bj.row_factory = sqlite3.Row
    dst = sqlite3.connect(str(OUT_DB))
    try:
        create_schema(dst)
        item_chap_ids = build_chapters(dst, fw)
        print(f"[OK] 建立章节：{len(item_chap_ids)} 个 enterprise_item 子目")
        stats = copy_norms_and_deps(dst, bj, item_chap_ids)
        print(f"[OK] 迁移：{stats['norms']} 条 Norm / {stats['contents']} 条 Content / {stats['cons']} 条 Consumption")
        if stats["unmapped_chapters"]:
            print(f"\n[UNMAPPED] {len(stats['unmapped_chapters'])} 个章节未映射, 共 {stats['unmapped_norms']} 条 norm:")
            for cid, n in stats["unmapped_chapters"][:30]:
                name = bj.execute("SELECT chap_Name FROM chapter WHERE chap_ID=?", (cid,)).fetchone()
                print(f"  {cid} {name[0] if name else '?'} ({n} 条)")
            if len(stats["unmapped_chapters"]) > 30:
                print(f"  ... 还有 {len(stats['unmapped_chapters']) - 30} 条")
        else:
            print("[OK] 所有 Beijing book15-19 有定额的章节均已映射")
    finally:
        fw.close(); bj.close(); dst.close()
    print(f"\n[DONE] {OUT_DB}")


if __name__ == "__main__":
    main()
